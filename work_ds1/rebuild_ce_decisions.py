"""Materialize the analyst's per-artifact CodeErrors decisions.

The mapping below is keyed by released artifact_id, never by corpus row number.
It was reviewed against each artifact's task contract, incorrect source and
reference source.  AST is used only for the CE02 structural check.
"""
from __future__ import annotations

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / 'work_ds1'


def read_jsonl(path):
    return [json.loads(line) for line in path.open(encoding='utf-8') if line.strip()]


def incorrect_source(artifact):
    content = artifact['content']
    start = content.index('Incorrect Code (Generated by LLM):\n') + len('Incorrect Code (Generated by LLM):\n')
    end = content.index('\n\nCorrect Code (Ground Truth):', start)
    return content[start:end]


