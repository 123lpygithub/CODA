import ast, io, json, sys, tokenize
from collections import OrderedDict

rows=list(map(json.loads,open('work_ds1/corpus/codeerrors.jsonl',encoding='utf-8')))

def strip_docstrings(src):
    try:
        tree=ast.parse(src)
    except SyntaxError:
        return src
    lines=src.splitlines(keepends=True)
    spans=[]
    for node in ast.walk(tree):
        if isinstance(node,(ast.Module,ast.FunctionDef,ast.AsyncFunctionDef,ast.ClassDef)) and node.body:
            first=node.body[0]
            if isinstance(first,ast.Expr) and isinstance(first.value,ast.Constant) and isinstance(first.value.value,str):
                spans.append((first.lineno-1, first.end_lineno))
    if not spans: return src
    out=[]; skip=set()
    for a,b in spans: skip.update(range(a,b))
    for i,line in enumerate(lines):
        if i not in skip: out.append(line)
    return ''.join(out)

def compact(s):
    lines=s.splitlines(); out=[]; prev=None; rep=0
    for line in lines:
        if line.strip()=='' and prev is not None and prev.strip()=='':
            continue
        if line==prev:
            rep+=1; continue
        if rep:
            out.append(f'    [previous line repeated {rep} more time(s)]'); rep=0
        out.append(line); prev=line
    if rep: out.append(f'    [previous line repeated {rep} more time(s)]')
    return '\n'.join(out)

def executable_summary(src):
    try:
        tree=ast.parse(src)
    except SyntaxError as e:
        return f'SYNTAX ERROR: {e}'
    kinds=[]
    for node in ast.walk(tree):
        if isinstance(node,ast.Return): kinds.append('return')
        elif isinstance(node,ast.Raise): kinds.append('raise')
        elif isinstance(node,ast.If): kinds.append('if')
        elif isinstance(node,(ast.For,ast.While)): kinds.append('loop')
        elif isinstance(node,ast.Assign): kinds.append('assign')
        elif isinstance(node,ast.Expr) and not (isinstance(node.value,ast.Constant)): kinds.append('expr')
    return ', '.join(sorted(set(kinds))) or 'no executable statements'

tasks=OrderedDict()
for i,r in enumerate(rows,1):
    tid=int(r['raw_fields']['task_id'])
    tasks.setdefault(tid,[]).append((i,r))

lo,hi=int(sys.argv[1]),int(sys.argv[2])
for tid,items in tasks.items():
    if not lo<=tid<=hi: continue
    f=items[0][1]['raw_fields']
    print('\n'+'#'*110)
    print(f'TASK {tid} | {len(items)} artifacts')
    print('DESCRIPTION')
    print(compact(strip_docstrings(f['task_description'])))
    print('CORRECT CODE')
    print(compact(strip_docstrings(f['ground_truth_code'])))
    for i,r in items:
        c=r['content']; s=c.index('Incorrect Code (Generated by LLM):\n')+len('Incorrect Code (Generated by LLM):\n'); e=c.index('\n\nCorrect Code (Ground Truth):',s)
        inc=c[s:e]; body=strip_docstrings(inc)
        print('\n'+'='*110)
        print(f"ROW {i} | ARTIFACT {r['artifact_id']} | MODEL {r['raw_fields']['model']} | AST: {executable_summary(body)}")
        print(compact(body))
