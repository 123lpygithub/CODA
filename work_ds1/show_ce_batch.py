import json, sys, re
from collections import OrderedDict
rows=list(map(json.loads,open('work_ds1/corpus/codeerrors.jsonl',encoding='utf-8')))
lo,hi=int(sys.argv[1]),int(sys.argv[2])
tasks=OrderedDict()
for r in rows:
    tid=int(r['raw_fields']['task_id'])
    if lo<=tid<=hi:
        tasks.setdefault(tid,[]).append(r)

def compact(s):
    lines=s.splitlines()
    out=[]
    prev=None; rep=0
    for line in lines:
        if line==prev:
            rep+=1
            continue
        if rep:
            out.append(f'    [previous line repeated {rep} more time(s)]')
            rep=0
        out.append(line); prev=line
    if rep: out.append(f'    [previous line repeated {rep} more time(s)]')
    return '\n'.join(out)

for tid,items in tasks.items():
    f=items[0]['raw_fields']
    print('\n'+'#'*100)
    print(f'TASK {tid} | artifacts {len(items)}')
    print('DESCRIPTION')
    print(f['task_description'])
    print('CORRECT CODE')
    print(compact(f['ground_truth_code']))
    for r in items:
        c=r['content']
        s=c.index('Incorrect Code (Generated by LLM):\n')+len('Incorrect Code (Generated by LLM):\n')
        e=c.index('\n\nCorrect Code (Ground Truth):',s)
        print('\n'+'='*100)
        print(f"ARTIFACT {r['artifact_id']} | model {r['raw_fields']['model']}")
        print(compact(c[s:e]))
