import ast, json, sys
rows=list(map(json.loads,open('work_ds1/corpus/codeerrors.jsonl',encoding='utf-8')))
tasks={}
for i,r in enumerate(rows,1): tasks.setdefault(int(r['raw_fields']['task_id']),[]).append((i,r))
def strip_doc(src):
    try: tree=ast.parse(src)
    except SyntaxError: return src
    lines=src.splitlines(keepends=True); skip=set()
    for n in ast.walk(tree):
        if isinstance(n,(ast.Module,ast.FunctionDef,ast.AsyncFunctionDef,ast.ClassDef)) and n.body:
            f=n.body[0]
            if isinstance(f,ast.Expr) and isinstance(f.value,ast.Constant) and isinstance(f.value.value,str):
                skip.update(range(f.lineno-1,f.end_lineno))
    return ''.join(x for i,x in enumerate(lines) if i not in skip)
def compact(s):
    out=[]; prev=None; rep=0
    for line in s.splitlines():
        if line==prev: rep+=1; continue
        if rep: out.append(f'    [repeat x{rep}]'); rep=0
        out.append(line); prev=line
    if rep: out.append(f'    [repeat x{rep}]')
    return '\n'.join(out)
def inc(r):
    c=r['content']; a=c.index('Incorrect Code (Generated by LLM):\n')+len('Incorrect Code (Generated by LLM):\n'); b=c.index('\n\nCorrect Code (Ground Truth):',a); return c[a:b]
tids=[int(x) for x in sys.argv[1:]]
for tid in tids:
    items=tasks[tid]; f=items[0][1]['raw_fields']
    print('\n'+'#'*100); print(f'TASK {tid} | {len(items)} artifacts')
    print('DESCRIPTION'); print(compact(strip_doc(f['task_description'])))
    print('CORRECT'); print(compact(strip_doc(f['ground_truth_code'])))
    for i,r in items:
        print('\n'+'-'*100); print(f"ROW {i} ARTIFACT {r['artifact_id']} {r['raw_fields']['model']}")
        print(compact(strip_doc(inc(r))))
