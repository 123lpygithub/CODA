"""Freeze the three corpora exactly as read. No classification, no keywords."""
import csv, json, hashlib, os
from pathlib import Path

ROOT = Path('/home/peiyuan/CODA/FSE27-CODA/CODA')
OUT = ROOT/'work_ds1'/'corpus'; OUT.mkdir(parents=True, exist_ok=True)

def sha(s): return hashlib.sha256(s.encode()).hexdigest()

# ---------- CodeErrors: one artifact per unique (task_id, model, incorrect_code) ----------
rows = json.load(open(ROOT/'dataset/llm_code_error_semantic/llm_code_error_semantic.json'))
groups = {}
for r in rows:
    key = (str(r['task_id']), r['model'], r['incorrect_code'])
    groups.setdefault(key, []).append(r)
reps = sorted((min(v, key=lambda x: int(x['id'])) for v in groups.values()), key=lambda x: int(x['id']))
with open(OUT/'codeerrors.jsonl','w') as f:
    for r in reps:
        members = sorted(int(x['id']) for x in groups[(str(r['task_id']), r['model'], r['incorrect_code'])])
        content = ("Task Description:\n%s\n\nIncorrect Code (Generated by LLM):\n%s\n\nCorrect Code (Ground Truth):\n%s"
                   % (r['task_description'], r['incorrect_code'], r['ground_truth_code']))
        rec = {'artifact_id': str(r['id']), 'content': content,
               'raw_fields': {'task_id': str(r['task_id']), 'model': r['model'],
                              'task_description': r['task_description'],
                              'incorrect_code': r['incorrect_code'],
                              'ground_truth_code': r['ground_truth_code']},
               'source_error_ids': members}
        f.write(json.dumps(rec, ensure_ascii=False)+'\n')
print('codeerrors', len(reps), 'from', len(rows))

# ---------- SATD ----------
srows = list(csv.DictReader(open(ROOT/'dataset/ml_satd_23_shades/source/sampled_label_dataset.csv', encoding='utf-8')))
with open(OUT/'satd.jsonl','w') as f:
    for i, r in enumerate(srows, 1):
        aid = f"23shades-{i:04d}-{r['Dataset ID']}"
        content = ("Repository type: %s\nRepository: %s\nFile: %s\n\nSelf-admitted technical-debt comment:\n%s"
                   % (r['Repo Type'], r['Repo Name'], r['Filename'], r['Comment Text']))
        rec = {'artifact_id': aid, 'content': content,
               'raw_fields': {k: r[k] for k in ('Dataset ID','Repo Type','Repo Name','Filename',
                                                'Comment-Introducing Revision','Comment-Removing Revision','Comment Text')}}
        f.write(json.dumps(rec, ensure_ascii=False)+'\n')
print('satd', len(srows))

# ---------- Privacy ----------
P = ROOT/'dataset/personal_data_protection_github'
text = open(P/'source/extracted/coded_issue_data.csv', encoding='utf-8-sig').read()
lines = text.splitlines()
header = lines[0].split(';')
recs = list(csv.DictReader(lines, delimiter=';'))
print('privacy rows', len(recs), 'cols', len(header))
snap = P/'source/github_snapshot_20261106_v10'
manifest = json.load(open(snap/'manifest.json'))['artifacts']
with open(OUT/'privacy.jsonl','w') as f:
    for r in recs:
        aid = f"privacy-issue-{r['index']}"
        m = manifest.get(aid, {})
        body = '[Issue body not retrieved.]'; disc = '[Issue discussion not retrieved.]'
        status='metadata_only'; n_ret=0; n_exp='unknown'; scope='Released title and metadata only.'
        if m.get('file'):
            s = json.load(open(snap/m['file']))
            status = s['evidence_status']; n_ret = s['retrieved_comment_count']; n_exp = s['expected_comment_count']
            scope = s['scope']
            body = s['body'] or '[Empty issue body.]'
            if s['comments']:
                disc = '\n\n'.join('Comment %d | created %s\nSource: %s\n%s' % (i, c['created_at'], c['url'], c['body'] or '[Empty comment body.]')
                                   for i, c in enumerate(s['comments'], 1))
            else:
                disc = '[No issue comments at retrieval time.]' if s['comments_complete'] else '[Issue comments not fully retrieved.]'
        content = ("Released issue metadata:\nIssue title: %s\nProject: %s\nIssue type: %s\nMatched keywords: %s\n"
                   "GitHub labels: %s\nStatus in release: %s\nComments in release: %s; discussants: %s\n"
                   "Reported: %s; last active: %s\nIssue number: %s\n\n"
                   "Supplemental evidence: %s | comments retrieved %s/%s\nScope: %s\n\nIssue body:\n%s\n\nIssue discussion:\n%s"
                   % (r['title'], r['project'], r['type'], r['keywords'], r['labels'], r['status'],
                      r['#comments'], r['#discussants'], r['reporting_date'], r['last_active_date'], r['issue_number'],
                      status, n_ret, n_exp, scope, body, disc))
        rec = {'artifact_id': aid, 'content': content,
               'raw_fields': {'title': r['title'], 'project': r['project'], 'type': r['type'],
                              'keywords': r['keywords'], 'github_labels': r['labels'],
                              'status': r['status'], 'issue_number': r['issue_number'],
                              'evidence_status': status, 'body': body, 'discussion': disc}}
        f.write(json.dumps(rec, ensure_ascii=False)+'\n')
print('privacy', len(recs))
for n in ('codeerrors','satd','privacy'):
    p = OUT/(n+'.jsonl')
    ls = p.read_text().splitlines()
    tot = sum(len(json.loads(l)['content']) for l in ls)
    print(n, len(ls), 'records', tot, 'chars', 'sha', hashlib.sha256(p.read_bytes()).hexdigest()[:16])
