"""Render human-readable CODEBOOK.md and METHOD.md from generated JSON."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'Artifact'
ANALYST = 'deepseek-1'
DATASETS = ['CodeErrors', 'SATD', 'Privacy']


def read_jsonl(path):
    return [json.loads(line) for line in path.open(encoding='utf-8') if line.strip()]


def dataset_label(dataset):
    return {'CodeErrors': 'CodeErrors', 'SATD': 'SATD', 'Privacy': 'Privacy'}[dataset]


def render_codebook(dataset):
    base = OUT / dataset / ANALYST
    book = json.loads((base / 'codebook.json').read_text(encoding='utf-8'))
    assignments = read_jsonl(base / 'assignments.jsonl')
    coverage = json.loads((base / 'coverage_report.json').read_text(encoding='utf-8'))
    covered_codes = [code for code in book['codes'] if code['artifact_count'] > 0]
    total_assign = sum(len(x['code_ids']) for x in assignments)
    multi = sum(1 for x in assignments if len(x['code_ids']) > 1)
    lines = []
    lines.append(f'# {dataset_label(dataset)} — 逐条阅读归纳的 codebook（{ANALYST}）')
    lines.append('')
    lines.append(f'{book["artifact_count"]} 个 artifact · 定义 {book["code_count"]} 个主题代码（其中 {len(covered_codes)} 个在本批有成员） · {total_assign} 条 artifact–code 成员关系 · {multi} 条多标签 artifact。')
    lines.append('')
    lines.append('本版来自逐条完整阅读、开放编码、持续比较与显式归并。每条 artifact 至少有一个代码；允许在材料支持多个独立机制时多标签。脚本只序列化人工判断并校验数量、成员与逐字证据，不依据关键词、正则、发布标签或旧分类自动决定类别；旧底稿只用于对照复核，所有边界判断均回到冻结原文。')
    lines.append('')
    lines.append('本版是一个 AI 编码者的材料归纳，不是独立人工双编码，也不把“结构校验通过”表述为解释唯一或法律/安全事实已被验证。')
    lines.append('')
    lines.append('## 类别一览')
    lines.append('')
    lines.append('|Code|类别|覆盖 artifact 数|')
    lines.append('|---|---|---:|')
    for code in book['codes']:
        lines.append(f'|{code["code_id"]}|{code["name"]}|{code["artifact_count"]}|')
    lines.append('')
    lines.append('## 使用规则')
    lines.append('')
    if dataset == 'CodeErrors':
        lines.append('- 分析单位是去重后的一个错误解法；同一任务的不同模型/不同错误源码分别保留。')
        lines.append('- 代码描述可从源码直接观察到的失败机制，不根据模型名、任务编号或数据集旧标签决定类别。')
        lines.append('- 目标被替换（CE05）与同一目标下的覆盖不足（CE06）、公式错误（CE09）分开；确实同时存在时多标签。')
        lines.append('- 语法截断（CE02）与未交付实现（CE01）可并存；未定义名称（CE03）与类型协议错误（CE12）也可并存。')
        lines.append('- 证据统一取冻结内容中 “Incorrect Code (Generated by LLM)” 到 “Correct Code (Ground Truth)” 之间的完整错误源码。')
    elif dataset == 'SATD':
        lines.append('- 分析单位是一条 SATD 注释；`TODO`、`FIXME`、`HACK` 只是语用线索，不能自动决定类别。')
        lines.append('- 明确未完成、已知错误、改进机会、开放决策与普通解释性注释必须区分。')
        lines.append('- 允许一个注释包含多个独立机制，例如“补测试 + 移除旧依赖”或“兼容性缺陷 + 性能优化”。')
        lines.append('- 只有标记、名词或无法解释的改进判断用 SATD-17；有明确对象和动作时按机制编码。')
        lines.append('- 证据统一取冻结内容中的完整 SATD 注释，避免从短注释中再截出失去语境的关键词。')
    else:
        lines.append('- 分析单位是一个发布 issue；同一文本重复出现时仍保留独立 artifact ID。')
        lines.append('- 主题代码描述材料涉及的隐私机制与治理问题，不等于已确认的漏洞、合规结论或实施结果。')
        lines.append('- `outcome` 与 `evidence_availability` 独立记录；`closed`、标签或合并 PR 不能自动等同修复已验证。')
        lines.append('- 只有标题/元数据的条目只能支持标题可见的议题；不得由匹配关键词补出正文机制。')
        lines.append('- 反例、争议和归因修正用 PRIVACY-Y 记录，但不表示残余风险消失；内容不足用 PRIVACY-Z，并保留证据可用性。')
        lines.append('- 证据是逐条选定的原文片段，可能只支持分析的一部分；完整上下文仍在 `artifacts.jsonl`。')
    lines.append('')
    for code in book['codes']:
        lines.append(f'## {code["code_id"]} {code["name"]}')
        lines.append('')
        lines.append(code['definition'])
        lines.append('')
        lines.append(f'- 纳入：{code["inclusion_criteria"]}')
        lines.append(f'- 排除与边界：{code["exclusion_criteria"]}；{code["boundary_examples"]}')
        lines.append(f'- 支持：{code["artifact_count"]} 个 artifact。完整成员见 `codebook.json` 的 `artifact_ids`。')
        lines.append('')
    lines.append('## 文件说明')
    lines.append('')
    lines.append('- `codebook.json`：代码定义、边界与全部成员 ID。')
    lines.append('- `assignments.jsonl`：逐条代码、开放代码、备忘录、逐字证据、内容哈希与分析依据。')
    lines.append('- `artifacts.jsonl`：冻结语料原文。')
    lines.append('- `memberships.csv`：artifact–code 长表。')
    lines.append('- `artifact_index.csv`、`reading_memos.csv`：便于浏览与复核的索引。')
    lines.append('- `coverage_report.json`：数量、缺失、重复、未定义代码、证据与双向成员校验。')
    lines.append('- `METHOD.md`：实际执行过程、材料边界与限度。')
    lines.append('')
    (base / 'CODEBOOK.md').write_text('\n'.join(lines), encoding='utf-8')


def render_method(dataset):
    base = OUT / dataset / ANALYST
    book = json.loads((base / 'codebook.json').read_text(encoding='utf-8'))
    assignments = read_jsonl(base / 'assignments.jsonl')
    coverage = json.loads((base / 'coverage_report.json').read_text(encoding='utf-8'))
    covered_codes = [code for code in book['codes'] if code['artifact_count'] > 0]
    lines = []
    lines.append(f'# {dataset_label(dataset)} · {ANALYST} · 方法与限度')
    lines.append('')
    lines.append(f'本版覆盖 {len(assignments)} 个 artifact，形成 {book["code_count"]} 个主题代码与 {sum(len(x["code_ids"]) for x in assignments)} 条 artifact–code 成员关系。')
    lines.append('')
    lines.append('## 实际执行的方法')
    lines.append('')
    if dataset == 'CodeErrors':
        lines.append('1. 从 `dataset/llm_code_error_semantic/llm_code_error_semantic.json` 读取来源记录，按 `(task_id, model, incorrect_code)` 去重，冻结为 557 个独立解法，覆盖 150 个任务。')
        lines.append('2. 逐条阅读任务契约、错误源码与正确源码；先写该条开放描述，再比较不同任务中反复出现的失败机制。')
        lines.append(f'3. 预先定义 {book["code_count"]} 个代码；本批实际观察到 {len(covered_codes)} 个有成员代码。未观察到的代码保留定义与零成员，不虚构成员。')
        lines.append('4. 对每个 artifact 的任一改动都按 artifact_id 重新核验契约与源码；发现旧决策文件的注释与 artifact_id 错位后，按冻结源码重建，而不是沿用行号对应。')
        lines.append('5. 用 `ce_doctest_results.json` 中的 doctest 运行结果作辅助诊断，但运行失败、通过或无法加载都没有被用作自动分类规则。')
    elif dataset == 'SATD':
        lines.append('1. 从 `dataset/ml_satd_23_shades/source/sampled_label_dataset.csv` 读取 856 条 SATD 注释，冻结为 856 个 artifact。')
        lines.append('2. 逐条完整阅读注释，记录对象、动作、原因、完成标准以及不确定程度；不把 `TODO` 字面量当作类别。')
        lines.append('3. 在阅读过程中持续比较，把开放描述归并为 18 个技术债机制；对只有标记或证据不足的条目保留 SATD-17。')
        lines.append('4. 对多机制注释进行多标签，并反向检查每个代码的全部成员，确认没有仅凭单个关键词误收。')
        lines.append('5. 每条证据由构建脚本从冻结 `content` 中定位完整 SATD 注释，并记录字符偏移；短注释不额外截取关键词。')
    else:
        lines.append('1. 从 `dataset/personal_data_protection_github/source/extracted/coded_issue_data.csv` 选取 `is_privacy_related == true` 的 652 条 issue，并从 `source/github_snapshot_20261106_v10/issues/*.json` 拼接正文、评论和发布元数据，冻结为 652 个 artifact。')
        lines.append('2. 按 artifact 顺序分批完整阅读全部可用文本，包括长讨论、粘贴代码、日志、后续更正与反驳；逐条记录开放代码、分析备忘录、结果与证据可用性。')
        lines.append('3. 阅读完成后把开放代码归并为 11 个主题代码，保留多标签、反例和争议，不把参与者法律主张、`closed` 状态或合并 PR 改写成已验证事实。')
        partial = coverage.get('evidence_availability', {}).get('partial', 0)
        complete = coverage.get('evidence_availability', {}).get('complete', 0)
        lines.append(f'4. 对 {partial} 条部分证据条目逐条重读冻结正文与评论；证据只覆盖标题/元数据时仅支持标题可见的议题，无法定位具体机制的条目才使用 PRIVACY-Z，不由匹配关键词补出内容。')
        lines.append('5. 对每条证据在当前冻结 `content` 中重新定位并计算字符偏移；不沿用其他结果包的坐标。')
    lines.append('')
    lines.append('## 编码原则')
    lines.append('')
    lines.append('- 分析单位与去重口径见 `codebook.json` 的 `unit`；同文重复不合并。')
    lines.append('- 一个 artifact 可多标签；多标签只表示材料支持多个独立机制，不表示因果排序。')
    lines.append('- 类别定义、纳入/排除和边界示例先于成员检查固定；遇到相邻案例时回到定义比较，而不是按关键词投票。')
    lines.append('- 负例、证据不足和未决状态被保留；没有为了覆盖率强行给出具体机制。')
    lines.append('- 证据必须是冻结 `content` 的逐字子串；证据片段不等于完整语境，完整原文见 `artifacts.jsonl`。')
    lines.append('')
    lines.append('## 材料边界与解释限制')
    lines.append('')
    if dataset == 'Privacy':
        lines.append('- 652 条来自适配器选出的隐私相关 issue，不是上游全部 issue；抓取快照是 2026-11-06 的当前可获取版本，不是原论文历史时点的完整复现。')
        partial = coverage.get('evidence_availability', {}).get('partial', 0)
        complete = coverage.get('evidence_availability', {}).get('complete', 0)
        lines.append(f'- {complete} 条完整、{partial} 条部分证据；所有本地可用文本已逐条阅读。外部网页、图片、视频、附件和链接 PR 内容未获取，不计为已阅读。')
        lines.append('- 标题/元数据、作者陈述、法律解释、安全承诺和“无 PII”主张都保留其来源地位，不自动升级为已验证事实。')
        lines.append('- 代码表示材料涉及的主题，不代表风险成立、措施实施或问题已解决；结果字段单独记录完成状态。')
    elif dataset == 'SATD':
        lines.append('- SATD 注释可能简短、截断或缺少上下文；无法解释的对象不凭项目名或文件名猜测。')
        lines.append('- 注释承认债务不等于债务后来被偿还；本 codebook 只描述注释中的债务机制。')
    else:
        lines.append('- 错误判断以提供的任务契约、错误源码与正确源码为依据；不运行隐藏测试，也不假设外部 harness 提供未声明名称。')
        lines.append('- 同一 artifact 可以同时存在多个失败机制；代码不声称覆盖所有可能输入。')
        lines.append('- doctest 结果只用于辅助核对，不是分类依据，也不替代对源码的逐条阅读。')
    lines.append('- 本版是一个 AI 编码者的质性分析，没有独立人工双编码、访谈、饱和度实验或编码者一致性统计；结构校验不能替代这些质量控制。')
    lines.append('')
    lines.append('## 与旧结果的关系')
    lines.append('')
    if dataset == 'CodeErrors':
        lines.append('本版以既有分析底稿为起点重新判读，但发现旧决策文件存在行号与 `artifact_id` 错位后，改用冻结源码按 `artifact_id` 重建 `ce.jsonl`；旧标签没有被当作分类依据。')
    elif dataset == 'SATD':
        lines.append('本版以既有 SATD 决策底稿为起点，逐条对照冻结注释复核并修正边界条目；类别名称与成员仍由本版显式判断，不把旧标签当作自动规则。')
    else:
        lines.append('本版以既有 Privacy 决策底稿为起点，逐条对照冻结 issue 正文与评论复核，并修正反例归属与高标签边界；旧标签没有被当作自动规则。')
    lines.append('')
    (base / 'METHOD.md').write_text('\n'.join(lines), encoding='utf-8')


def main():
    for dataset in DATASETS:
        render_codebook(dataset)
        render_method(dataset)


if __name__ == '__main__':
    main()
