import json, sys
rows=list(map(json.loads,open('work_ds1/corpus/codeerrors.jsonl',encoding='utf-8')))
lo,hi=int(sys.argv[1]),int(sys.argv[2])
def compact(s):
    lines=s.splitlines(); out=[]; prev=None; rep=0
    for line in lines:
        if line==prev:
            rep+=1; continue
        if rep:
            out.append(f'    [previous line repeated {rep} more time(s)]'); rep=0
        out.append(line); prev=line
    if rep: out.append(f'    [previous line repeated {rep} more time(s)]')
    return '\n'.join(out)
for i,r in enumerate(rows,1):
    if not lo<=i<=hi: continue
    f=r['raw_fields']; c=r['content']
    s=c.index('Incorrect Code (Generated by LLM):\n')+len('Incorrect Code (Generated by LLM):\n')
    e=c.index('\n\nCorrect Code (Ground Truth):',s)
    print('\n'+'#'*100)
    print(f"ROW {i} | ARTIFACT {r['artifact_id']} | TASK {f['task_id']} | MODEL {f['model']}")
    print('TASK DESCRIPTION')
    print(compact(f['task_description']))
    print('CORRECT CODE')
    print(compact(f['ground_truth_code']))
    print('INCORRECT CODE')
    print(compact(c[s:e]))
