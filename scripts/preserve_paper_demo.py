"""Preserve an unchanged CODA run for the paper's interface walkthrough."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tempfile
from datetime import datetime, timezone
from pathlib import Path


def fingerprints(root: Path) -> dict[str, str]:
    result: dict[str, str] = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"Refusing to preserve a symlink: {path.relative_to(root)}")
        if path.is_file():
            result[path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return result


def preserve(source: Path, destination_root: Path) -> Path:
    source = source.resolve(strict=True)
    checkpoint = json.loads((source / "checkpoint.json").read_text(encoding="utf-8"))
    run_id = checkpoint["run_id"]
    if not isinstance(run_id, str) or run_id in {"", ".", ".."} or Path(run_id).name != run_id:
        raise ValueError("The checkpoint must contain a single-component run_id.")
    destination_root = destination_root.resolve()
    if destination_root == source or source in destination_root.parents:
        raise ValueError("The destination must be outside the source run.")
    bootstrap = checkpoint.get("metadata", {}).get("bootstrap", {})
    if bootstrap.get("status") in {"running", "cancelling"} or checkpoint.get("status") == "in_progress":
        raise ValueError("Stop background processing before preserving a run.")
    destination_root.mkdir(parents=True, exist_ok=True)
    destination = destination_root / run_id
    if destination.exists():
        raise FileExistsError(f"The demo already exists; nothing was overwritten: {destination}")
    before = fingerprints(source)
    # Compare both trees after copying so a changing source is never published.
    with tempfile.TemporaryDirectory(prefix=".paper-demo-", dir=destination_root) as temp:
        staging = Path(temp)
        copied = staging / run_id
        shutil.copytree(source, copied)
        if fingerprints(copied) != before or fingerprints(source) != before:
            raise RuntimeError("The source changed during preservation. Stop processing and retry.")
        manifest = {
            "purpose": "Interface screenshot working copy; excluded from experimental results",
            "preserved_at": datetime.now(timezone.utc).isoformat(),
            "source_run": str(source),
            "run_id": run_id,
            "dataset_name": checkpoint.get("dataset_name"),
            "status_at_preservation": checkpoint.get("status"),
            "bootstrap_status_at_preservation": bootstrap.get("status"),
            "original_records_modified": False,
            "human_approvals_added": False,
            "sha256": before,
        }
        manifest_path = destination_root / f"{run_id}.snapshot.json"
        if manifest_path.exists():
            raise FileExistsError(f"A snapshot manifest already exists: {manifest_path}")
        with manifest_path.open("x", encoding="utf-8") as stream:
            json.dump(manifest, stream, ensure_ascii=False, indent=2)
            stream.write("\n")
        try:
            copied.rename(destination)
        except BaseException:
            manifest_path.unlink()
            raise
    return destination


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_run", type=Path, help="Stopped ordinary run directory")
    parser.add_argument("--destination-root", type=Path, default=Path("runs/paper-demo"))
    args = parser.parse_args()
    try:
        destination = preserve(args.source_run, args.destination_root)
    except (OSError, ValueError, KeyError, RuntimeError) as exc:
        parser.exit(1, f"Cannot preserve paper demo: {exc}\n")
    print(f"Preserved unchanged run: {destination}")
    print(f"Start an isolated API with --runs-root {destination.parent}")
    print("No model calls or review decisions were generated by this command.")


if __name__ == "__main__":
    main()
